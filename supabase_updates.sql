-- 3. View para Admin Stats (Opcional, mas útil)
-- Drop se existir para recriar
DROP VIEW IF EXISTS admin_stats_view;

CREATE OR REPLACE VIEW admin_stats_view AS
SELECT
  (SELECT count(*) FROM usuarios WHERE tipo = 'usuario') as total_users,
  (SELECT count(*) FROM usuarios WHERE tipo = 'compositor') as total_composers,
  (SELECT count(*) FROM hinos) as total_songs,
  (SELECT COALESCE(SUM(plays_count), 0) FROM hinos) as total_plays, -- assumindo coluna plays_count
  (SELECT count(*) FROM hinos WHERE ativo = true) as published_songs,
  (SELECT count(*) FROM reports WHERE status = 'open') as open_reports;
