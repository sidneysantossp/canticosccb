INSERT INTO public.bible_chapters (
  book_id,
  chapter_number,
  slug,
  is_published
)
SELECT
  b.id,
  chapter_number::smallint,
  chapter_number::text,
  false
FROM public.bible_books AS b
JOIN public.bible_translations AS t ON t.id = b.translation_id AND t.code = 'acf'
CROSS JOIN LATERAL generate_series(1, b.chapters_count::integer) AS chapter_number
ON CONFLICT (book_id, chapter_number) DO NOTHING;

