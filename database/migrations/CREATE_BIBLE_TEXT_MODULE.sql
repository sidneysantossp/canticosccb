-- --------------------------------------------------------------------------
-- RPC de leitura de capitulo: uma chamada retorna cabecalho e versiculos.
-- --------------------------------------------------------------------------
CREATE OR REPLACE FUNCTION public.get_bible_chapter(
  p_translation_code text,
  p_book_slug text,
  p_chapter_number integer
)
RETURNS TABLE (
  translation_code text,
  translation_name text,
  book_name text,
  book_slug text,
  book_abbreviation text,
  testament text,
  chapter_number integer,
  chapter_title text,
  chapter_slug text,
  verse_number integer,
  verse_text text,
  is_red_letter boolean,
  paragraph_number integer,
  section_title text,
  source_page integer
)
LANGUAGE sql
STABLE
SECURITY INVOKER
SET search_path = public
AS $$
  SELECT
    t.code::text,
    t.name::text,
    b.name::text,
    b.slug::text,
    b.abbreviation::text,
    b.testament::text,
    c.chapter_number::integer,
    c.title::text,
    c.slug::text,
    v.verse_number::integer,
    v.verse_text,
    v.is_red_letter,
    v.paragraph_number::integer,
    v.section_title::text,
    v.source_page
  FROM public.bible_translations AS t
  JOIN public.bible_books AS b ON b.translation_id = t.id
  JOIN public.bible_chapters AS c ON c.book_id = b.id
  JOIN public.bible_verses AS v ON v.chapter_id = c.id
  WHERE t.code = lower(btrim(p_translation_code))
    AND b.slug = lower(btrim(p_book_slug))
    AND c.chapter_number = p_chapter_number
    AND t.is_active = true
    AND t.is_published = true
    AND b.is_published = true
    AND c.is_published = true
  ORDER BY v.verse_number;
$$;

REVOKE ALL ON FUNCTION public.get_bible_chapter(text, text, integer) FROM PUBLIC;
GRANT EXECUTE ON FUNCTION public.get_bible_chapter(text, text, integer) TO anon, authenticated;

-- Busca textual em versiculos publicados.
CREATE OR REPLACE FUNCTION public.search_bible_verses(
  p_query text,
  p_translation_code text DEFAULT 'acf',
  p_limit integer DEFAULT 20
)
RETURNS TABLE (
  book_name text,
  book_slug text,
  chapter_number integer,
  chapter_slug text,
  verse_number integer,
  verse_text text,
  reference text,
  rank real
)
LANGUAGE sql
STABLE
SECURITY INVOKER
SET search_path = public
AS $$
  WITH search_query AS (
    SELECT websearch_to_tsquery('portuguese', btrim(p_query)) AS query
    WHERE length(btrim(p_query)) >= 2
  )
  SELECT
    b.name::text,
    b.slug::text,
    c.chapter_number::integer,
    c.slug::text,
    v.verse_number::integer,
    v.verse_text,
    concat(b.name, ' ', c.chapter_number, ':', v.verse_number)::text,
    ts_rank_cd(v.search_vector, q.query)::real
  FROM search_query AS q
  JOIN public.bible_verses AS v ON v.search_vector @@ q.query
  JOIN public.bible_chapters AS c ON c.id = v.chapter_id
  JOIN public.bible_books AS b ON b.id = c.book_id
  JOIN public.bible_translations AS t ON t.id = b.translation_id
  WHERE t.code = lower(btrim(p_translation_code))
    AND t.is_active = true
    AND t.is_published = true
    AND b.is_published = true
    AND c.is_published = true
  ORDER BY ts_rank_cd(v.search_vector, q.query) DESC, b.canon_order, c.chapter_number, v.verse_number
  LIMIT LEAST(GREATEST(COALESCE(p_limit, 20), 1), 100);
$$;

REVOKE ALL ON FUNCTION public.search_bible_verses(text, text, integer) FROM PUBLIC;
GRANT EXECUTE ON FUNCTION public.search_bible_verses(text, text, integer) TO anon, authenticated;

-- Relatorio administrativo de integridade antes da publicacao.
CREATE OR REPLACE FUNCTION public.validate_bible_translation(p_translation_code text)
RETURNS jsonb
LANGUAGE sql
STABLE
SECURITY INVOKER
SET search_path = public
AS $$
  WITH selected_translation AS (
    SELECT id FROM public.bible_translations WHERE code = lower(btrim(p_translation_code))
  ),
  counts AS (
    SELECT
      (SELECT count(*) FROM public.bible_books b WHERE b.translation_id IN (SELECT id FROM selected_translation)) AS books_count,
      (SELECT count(*) FROM public.bible_chapters c JOIN public.bible_books b ON b.id = c.book_id WHERE b.translation_id IN (SELECT id FROM selected_translation)) AS chapters_count,
      (SELECT count(*) FROM public.bible_verses v JOIN public.bible_chapters c ON c.id = v.chapter_id JOIN public.bible_books b ON b.id = c.book_id WHERE b.translation_id IN (SELECT id FROM selected_translation)) AS verses_count,
      (SELECT count(*) FROM public.bible_chapters c JOIN public.bible_books b ON b.id = c.book_id WHERE b.translation_id IN (SELECT id FROM selected_translation) AND c.verses_count = 0) AS empty_chapters_count,
      (SELECT count(*) FROM public.bible_books b WHERE b.translation_id IN (SELECT id FROM selected_translation) AND b.chapters_count <> (SELECT count(*) FROM public.bible_chapters c WHERE c.book_id = b.id)) AS books_with_chapter_mismatch
  )
  SELECT jsonb_build_object(
    'translation_code', lower(btrim(p_translation_code)),
    'books', books_count,
    'chapters', chapters_count,
    'verses', verses_count,
    'empty_chapters', empty_chapters_count,
    'books_with_chapter_mismatch', books_with_chapter_mismatch,
    'ready_to_publish', (
      books_count = 66
      AND chapters_count = 1189
      AND verses_count >= 30000
      AND empty_chapters_count = 0
      AND books_with_chapter_mismatch = 0
    )
  )
  FROM counts;
$$;

REVOKE ALL ON FUNCTION public.validate_bible_translation(text) FROM PUBLIC;
GRANT EXECUTE ON FUNCTION public.validate_bible_translation(text) TO authenticated;

