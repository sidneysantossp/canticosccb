INSERT INTO public.bible_books (
  translation_id,
  canon_order,
  testament,
  name,
  slug,
  abbreviation,
  chapters_count,
  is_published
)
SELECT
  acf.id,
  catalog.canon_order,
  catalog.testament,
  catalog.name,
  catalog.slug,
  catalog.abbreviation,
  catalog.chapters_count,
  false
FROM acf CROSS JOIN catalog
ON CONFLICT (translation_id, canon_order) DO UPDATE SET
  testament = EXCLUDED.testament,
  name = EXCLUDED.name,
  slug = EXCLUDED.slug,
  abbreviation = EXCLUDED.abbreviation,
  chapters_count = EXCLUDED.chapters_count,
  updated_at = now();

