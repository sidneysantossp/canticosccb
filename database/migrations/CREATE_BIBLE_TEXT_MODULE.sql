-- --------------------------------------------------------------------------
-- Traducao / edicao editorial.
-- --------------------------------------------------------------------------
CREATE TABLE IF NOT EXISTS public.bible_translations (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  code varchar(24) NOT NULL,
  name varchar(160) NOT NULL,
  short_name varchar(80) NOT NULL,
  language_code varchar(12) NOT NULL DEFAULT 'pt-BR',
  description text,
  copyright_holder text,
  rights_status varchar(40) NOT NULL DEFAULT 'pending_review',
  rights_basis text,
  license_name text,
  license_url text,
  attribution text,
  source_name text,
  source_url text,
  source_file_name text,
  editorial_notes text,
  is_active boolean NOT NULL DEFAULT true,
  is_published boolean NOT NULL DEFAULT false,
  published_at timestamptz,
  created_at timestamptz NOT NULL DEFAULT now(),
  updated_at timestamptz NOT NULL DEFAULT now(),
  CONSTRAINT bible_translations_code_unique UNIQUE (code),
  CONSTRAINT bible_translations_code_format CHECK (code = lower(code) AND code ~ '^[a-z0-9_-]+$'),
  CONSTRAINT bible_translations_rights_status_check CHECK (
    rights_status IN ('pending_review', 'user_declared_authorized', 'licensed', 'public_domain', 'open_license')
  ),
  CONSTRAINT bible_translations_publish_date_check CHECK (
    (is_published = false) OR (published_at IS NOT NULL)
  )
);

COMMENT ON TABLE public.bible_translations IS
  'Traducoes biblicas e seus dados editoriais, de origem, atribuicao e licenca.';

-- --------------------------------------------------------------------------
-- Livros. Cada traducao possui seu proprio catalogo para permitir futuras
-- traducoes sem alterar as URLs ou misturar textos.
-- --------------------------------------------------------------------------
CREATE TABLE IF NOT EXISTS public.bible_books (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  translation_id bigint NOT NULL REFERENCES public.bible_translations(id) ON DELETE CASCADE,
  canon_order smallint NOT NULL,
  testament varchar(24) NOT NULL,
  name varchar(100) NOT NULL,
  slug varchar(120) NOT NULL,
  abbreviation varchar(12) NOT NULL,
  chapters_count smallint NOT NULL,
  description text,
  is_published boolean NOT NULL DEFAULT false,
  created_at timestamptz NOT NULL DEFAULT now(),
  updated_at timestamptz NOT NULL DEFAULT now(),
  CONSTRAINT bible_books_translation_order_unique UNIQUE (translation_id, canon_order),
  CONSTRAINT bible_books_translation_slug_unique UNIQUE (translation_id, slug),
  CONSTRAINT bible_books_testament_check CHECK (testament IN ('old', 'new')),
  CONSTRAINT bible_books_order_check CHECK (canon_order BETWEEN 1 AND 66),
  CONSTRAINT bible_books_chapters_check CHECK (chapters_count BETWEEN 1 AND 150),
  CONSTRAINT bible_books_slug_format CHECK (slug ~ '^[a-z0-9]+(?:-[a-z0-9]+)*$')
);

COMMENT ON TABLE public.bible_books IS
  'Catalogo canonico dos 66 livros para cada traducao.';

-- --------------------------------------------------------------------------
-- Capitulos. O slug permite URLs como 1-a-criacao-do-mundo.
-- --------------------------------------------------------------------------
CREATE TABLE IF NOT EXISTS public.bible_chapters (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  book_id bigint NOT NULL REFERENCES public.bible_books(id) ON DELETE CASCADE,
  chapter_number smallint NOT NULL,
  title varchar(220),
  slug varchar(260) NOT NULL,
  summary text,
  verses_count smallint NOT NULL DEFAULT 0,
  is_published boolean NOT NULL DEFAULT false,
  created_at timestamptz NOT NULL DEFAULT now(),
  updated_at timestamptz NOT NULL DEFAULT now(),
  CONSTRAINT bible_chapters_book_number_unique UNIQUE (book_id, chapter_number),
  CONSTRAINT bible_chapters_book_slug_unique UNIQUE (book_id, slug),
  CONSTRAINT bible_chapters_number_check CHECK (chapter_number BETWEEN 1 AND 150),
  CONSTRAINT bible_chapters_verses_count_check CHECK (verses_count >= 0),
  CONSTRAINT bible_chapters_slug_format CHECK (slug ~ '^[0-9]+(?:-[a-z0-9]+)*$')
);

COMMENT ON TABLE public.bible_chapters IS
  'Metadados e estado editorial de cada capitulo.';

-- --------------------------------------------------------------------------
-- Versiculos. section_title e paragraph_number sustentam leitura editorial,
-- enquanto is_red_letter preserva as palavras de Jesus em vermelho.
-- --------------------------------------------------------------------------
CREATE TABLE IF NOT EXISTS public.bible_verses (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  chapter_id bigint NOT NULL REFERENCES public.bible_chapters(id) ON DELETE CASCADE,
  verse_number smallint NOT NULL,
  verse_text text NOT NULL,
  is_red_letter boolean NOT NULL DEFAULT false,
  paragraph_number smallint,
  section_title varchar(240),
  source_reference varchar(40),
  source_page integer,
  metadata jsonb NOT NULL DEFAULT '{}'::jsonb,
  search_vector tsvector GENERATED ALWAYS AS (
    to_tsvector('portuguese', COALESCE(verse_text, ''))
  ) STORED,
  created_at timestamptz NOT NULL DEFAULT now(),
  updated_at timestamptz NOT NULL DEFAULT now(),
  CONSTRAINT bible_verses_chapter_number_unique UNIQUE (chapter_id, verse_number),
  CONSTRAINT bible_verses_number_check CHECK (verse_number BETWEEN 1 AND 200),
  CONSTRAINT bible_verses_text_not_blank CHECK (length(btrim(verse_text)) > 0),
  CONSTRAINT bible_verses_paragraph_check CHECK (paragraph_number IS NULL OR paragraph_number >= 1),
  CONSTRAINT bible_verses_source_page_check CHECK (source_page IS NULL OR source_page >= 1)
);

COMMENT ON TABLE public.bible_verses IS
  'Texto de cada versiculo, com metadados de paragrafo, secao e palavras de Jesus.';

