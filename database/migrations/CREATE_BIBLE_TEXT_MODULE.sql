-- Mantem verses_count sincronizado sem depender do importador.
CREATE OR REPLACE FUNCTION public.refresh_bible_chapter_verses_count()
RETURNS trigger
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = public
AS $$
DECLARE
  affected_chapter_id bigint;
BEGIN
  IF TG_OP = 'DELETE' THEN
    affected_chapter_id := OLD.chapter_id;
  ELSE
    affected_chapter_id := NEW.chapter_id;
  END IF;

  UPDATE public.bible_chapters AS c
     SET verses_count = (
       SELECT count(*)::smallint
       FROM public.bible_verses AS v
       WHERE v.chapter_id = affected_chapter_id
     )
   WHERE c.id = affected_chapter_id;

  IF TG_OP = 'UPDATE' AND OLD.chapter_id IS DISTINCT FROM NEW.chapter_id THEN
    UPDATE public.bible_chapters AS c
       SET verses_count = (
         SELECT count(*)::smallint
         FROM public.bible_verses AS v
         WHERE v.chapter_id = OLD.chapter_id
       )
     WHERE c.id = OLD.chapter_id;
  END IF;

  IF TG_OP = 'DELETE' THEN
    RETURN OLD;
  END IF;

  RETURN NEW;
END;
$$;

DROP TRIGGER IF EXISTS bible_verses_refresh_chapter_count ON public.bible_verses;
CREATE TRIGGER bible_verses_refresh_chapter_count
AFTER INSERT OR UPDATE OF chapter_id OR DELETE ON public.bible_verses
FOR EACH ROW EXECUTE FUNCTION public.refresh_bible_chapter_verses_count();

