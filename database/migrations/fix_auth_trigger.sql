DROP POLICY IF EXISTS "Permitir leitura pública" ON public.usuarios;
DROP POLICY IF EXISTS "Permitir insert via trigger" ON public.usuarios;
DROP POLICY IF EXISTS "Permitir update próprio" ON public.usuarios;

