-- 1. Primeiro, vamos verificar se existe algum trigger na tabela auth.users
-- Execute esta query primeiro para ver os triggers existentes:
SELECT trigger_name, event_manipulation, action_statement 
FROM information_schema.triggers 
WHERE event_object_table = 'users' 
AND event_object_schema = 'auth';

-- 2. Se houver um trigger chamado "on_auth_user_created" ou similar,
-- ele pode estar tentando inserir na tabela usuarios e falhando.
